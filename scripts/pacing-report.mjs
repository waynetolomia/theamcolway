// Pacing report: plays a full journey through the real rules with today's plan only
// (no skipping, every planned mission passed first time) and reports how long each semester
// takes in study days and real weeks, and what XP, level and rank the cadet has reached.
//
//   node scripts/pacing-report.mjs        → writes docs/PACING.md
//
// It is a best case: real cadets will retry, miss days and play optional games, so real pacing is slower.
import { writeFileSync } from 'node:fs';
import { applyAction, createAccount, getAssignments, getSemesterProgress, getWeekStatus, getLomaProgress, activityQuestions } from '../public/game/course-progress.js';
import { ACTIVITIES, SEMESTERS } from '../public/game/book-course.js';
import { ORIENTATION_ROUTE, getNPCMission, getNPC } from '../public/game/npc-content.js';
import { getLomaGame } from '../public/game/loma-content.js';
import { plannedVariant } from '../public/game/curriculum.js';
import { BALANCE, RANKS, rankForLevel } from '../public/game/game-config.js';

const START = Date.parse('2026-10-19T02:00:00Z'); // a Monday morning in Bangkok
const DAY = 86_400_000;
const tokens = account => ({ expectedJourneyId: account.journey.journeyId, expectedDay: account.journey.day });
const proof = { completed: true, score: 100, completedCount: 8, total: 8 };
const answersOf = questions => Object.fromEntries(questions.map(q => [q.id, q.answers?.[0] ?? '']));

function act(account, payload, now) { return applyAction(account, { ...tokens(account), ...payload }, now, ACTIVITIES).account; }
function dress(account, outfit, now) {
  return account.journey.profile.outfit === outfit ? account : act(account, { action: 'profile', profile: { ...account.journey.profile, outfit } }, now);
}

function simulate(major) {
  let now = START;
  let account = applyAction(createAccount(now, `pacing-${major}-journey`), { action: 'init', profile: { name: 'Pacing Cadet', major } }, now, ACTIVITIES).account;
  for (const npcId of ORIENTATION_ROUTE) account = act(account, { action: 'introduceNPC', npcId }, now);
  const rows = [];
  let week = 0, studyDays = 0, lomaDays = 0, semesterStart = 0, guard = 0;
  while (!account.journey.graduated && guard++ < 1000) {
    const semester = account.journey.semester;
    let playedLoma = false;
    for (const item of getAssignments(account.journey, ACTIVITIES).plan) {
      if (item.status === 'done') continue;
      if (item.kind === 'book') {
        const activity = ACTIVITIES.find(a => a.id === item.id);
        account = dress(account, activity.location === 'workshop' ? 'coverall' : 'cadet', now);
        const variant = plannedVariant(activity, account.journey.journeyId, major);
        account = act(account, { action: 'complete', activityId: activity.id, answers: answersOf(activityQuestions(activity, variant)) }, now);
      } else if (item.kind === 'staff') {
        const mission = getNPCMission(item.id);
        account = dress(account, getNPC(mission.npcId)?.location === 'workshop' ? 'coverall' : 'cadet', now);
        account = act(account, { action: 'npcComplete', missionId: mission.id, answers: answersOf(mission.questions) }, now);
      } else if (item.kind === 'loma') {
        account = act(account, { action: 'completeLoma', gameId: item.id, answers: answersOf(getLomaGame(item.id).questions) }, now);
        playedLoma = true;
      }
    }
    // The Loma final begins once the last semester's book work is done.
    const final = getLomaProgress(account.journey, ACTIVITIES);
    if (final.available && !final.started) account = act(account, { action: 'startLoma', expectedMajor: major }, now);
    if (playedLoma) lomaDays++;
    if (getSemesterProgress(account.journey, ACTIVITIES).ready) {
      account = act(account, { action: 'advance', expectedSemester: semester }, now);
      rows.push({ semester, days: studyDays + 1 - semesterStart, cumulativeDays: studyDays + 1, weeks: week + 1, account });
      semesterStart = studyDays + 1;
      if (account.journey.graduated) break;
    }
    account = act(account, { action: 'fitness', kind: 'pt', proof }, now);
    account = act(account, { action: 'sleep', requestId: `pacing-${major}-${String(studyDays).padStart(4, '0')}` }, now);
    studyDays++;
    if (getWeekStatus(account, now).rest) { now += 7 * DAY; week++; }
  }
  return { rows, studyDays: studyDays + 1, weeks: week + 1, lomaDays, account };
}

async function xpOf(account) {
  const { publicState } = await import('../public/game/course-progress.js');
  return publicState(account, START, ACTIVITIES).rpg;
}

const lines = ['# Pacing report', '',
  'Generated by `node scripts/pacing-report.mjs`: a best-case journey through the real rules, playing only the daily plan and passing every mission first time. Real cadets will be slower.', '',
  `Balance: ${BALANCE.missions.perDay} missions per study day (${BALANCE.missions.staffSuggestedPerDay} staff suggestion), ${BALANCE.week.studyDays} study days per real week, ${BALANCE.missions.perWeek} missions per week; Loma final of ${BALANCE.loma.finalCount} games.`, ''];
for (const major of ['deck', 'engine']) {
  const run = simulate(major);
  lines.push(`## ${major.toUpperCase()} major`, '', '| Semester | Required book missions | Study days | Study days so far | Real weeks so far | XP | Level | Rank |', '|---|---:|---:|---:|---:|---:|---:|---|');
  for (const row of run.rows) {
    const rpg = await xpOf(row.account), meta = SEMESTERS.find(s => s.id === row.semester);
    lines.push(`| Y${meta.year} S${meta.term} | ${meta.activityIds.length} | ${row.days} | ${row.cumulativeDays} | ${row.weeks} | ${rpg.totalXp} | ${rpg.level} | ${rpg.rank} |`);
  }
  const final = await xpOf(run.account);
  lines.push('', `- Graduated: **${run.account.journey.graduated ? 'yes' : 'no'}** after ${run.studyDays} study days over ${run.weeks} real weeks.`,
    `- Loma final: ${run.lomaDays} study days with final games (minimum possible ${Math.ceil(BALANCE.loma.finalCount / BALANCE.missions.perDay)}).`,
    `- Final XP ${final.totalXp}, level ${final.level}, rank ${final.rank}. Highest rank available: ${RANKS.at(-1).title} (level ${RANKS.at(-1).level}).`, '');
  console.log(major, { studyDays: run.studyDays, weeks: run.weeks, lomaDays: run.lomaDays, xp: final.totalXp, level: final.level, rank: rankForLevel(final.level).title, graduated: run.account.journey.graduated });
}
writeFileSync(new URL('../docs/PACING.md', import.meta.url), lines.join('\n'));
console.log('Wrote docs/PACING.md');
