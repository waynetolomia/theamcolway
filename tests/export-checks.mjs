import assert from 'node:assert/strict';
import { readFileSync, readdirSync, statSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { spawnSync } from 'node:child_process';

const root = new URL('../', import.meta.url);
const read = path => readFileSync(new URL(path, root), 'utf8');
const manifest = JSON.parse(read('source-assets.json'));
assert.equal(manifest.sourceCommit, '3d7019d22655fb3b681f29e2eb0a977d040330c1');
// Beta changes: browser saves (local-academy.js / asset-paths.js), background music (music.js),
// creator gestures and the navy/gold creator theme. These original files are checked for
// their beta hooks instead of the original hash.
const BETA_EDITS = {
  'public/game/academy-api.js': ["import { academyFetch } from './local-academy.js';", 'fetcher = academyFetch }'],
  'public/game/app.js': ["import './asset-paths.js';", 'function saveNote()', "id=\"local-backup\"", "import { createMusic, MUSIC_TRACKS } from './music.js';", 'onGesture:', "CREATOR_STEPS=['name','customize','skills']"],
  'public/game/index.html': ['href="creator-theme.css"', 'href="minigames.css"', 'id="music-btn"', 'id="tab-skills"'],
  'public/game/world.js': ['playGesture(name)', '_applyGesture()', '_buildSignalMast()'],
  // Simplified mini-games generated by scripts/build-minigames.mjs (book activities kept in scripts/minigames/source).
  'public/game/book-course.js': ['"format":"choice"', '"generator":"scripts/build-minigames.mjs"'],
  'public/game/rpg-progress.js': ['Subject games train their own subject first.'],
  'public/game/fitness-games.js': ['export function createPtRhythm', 'data-pt-hold'],
  'public/game/campus.js': ['export const SHUTTLE_STATIONS', '...SHUTTLE_STATIONS'],
  'public/game/academy-ui.js': ["import { isLocalMode } from './local-academy.js';", 'href="/auth/login"'],
  // Daily mission plan, energy and weekly rest rules driven by public/game/game-config.js.
  'public/game/course-progress.js': ['export function computeDaily', "import { BALANCE } from './game-config.js';", "action === 'startMission'"],
  'public/game/loma-content.js': ['BALANCE.missions.perDay', 'BALANCE.loma.finalCount'],
  // Rule text updated for study days and shared mission slots.
  'public/game/character-dashboard.js': ['study days left', 'Each sleep ends a study day'],
  'public/game/loma-ui.js': ['Final games share your daily and weekly mission slots.', 'mission slots left today'],
  'public/game/lifeboat-ui.js': ['A new safety game uses one of today’s mission slots'],
};
let totalBytes = 0;
for (const item of manifest.files) {
  const file = new URL(item.path, root);
  let data = readFileSync(file);
  if (BETA_EDITS[item.path]) {
    const text = data.toString();
    for (const marker of BETA_EDITS[item.path]) assert.ok(text.includes(marker), `${item.path} is missing beta hook: ${marker}`);
    totalBytes += statSync(file).size;
    continue;
  }
  assert.equal(createHash('sha256').update(data).digest('hex'), item.sha256, `Source asset changed: ${item.path}`);
  assert.ok(statSync(file).size < 25 * 1024 * 1024, `Static asset exceeds Cloudflare's 25 MiB limit: ${item.path}`);
  totalBytes += statSync(file).size;
}
const config = JSON.parse(read('wrangler.jsonc'));
assert.equal(config.assets.directory, './public');
assert.equal(config.assets.binding, 'ASSETS');
assert.equal(config.assets.run_worker_first, true);
assert.equal(config.assets.not_found_handling, 'none');
assert.equal(config.assets.html_handling, 'none');
assert.equal(config.main, 'src/worker.mjs');
assert.equal(config.vars.ENVIRONMENT, 'production');
assert.ok(!config.vars.DEV_MODE);
assert.equal(config.preview_urls, false);
assert.deepEqual(readdirSync(new URL('migrations/', root)).sort(), [
  '0000_chubby_captain_flint.sql', '0001_huge_exiles.sql',
  '0002_class_worlds.sql', '0003_presence_reports.sql',
]);
assert.deepEqual(config.durable_objects.bindings, [{ name: 'PRESENCE_ROOMS', class_name: 'PresenceRoom' }]);
assert.deepEqual(config.migrations, [{ tag: 'presence-v1', new_sqlite_classes: ['PresenceRoom'] }]);
assert.equal(config.vars.STAFF_EMAILS, '');
assert.ok(!config.vars.DEV_ALLOW_USER_SWITCH);
assert.ok(!read('src/auth.mjs').includes("headers.get('oai-authenticated-user-id')"));
for (const options of [{}, { D1_DATABASE_ID: 'bad' }, {
  D1_DATABASE_ID: '12345678-1234-1234-1234-123456789abc', DEV_MODE: 'true',
}, {
  D1_DATABASE_ID: '12345678-1234-1234-1234-123456789abc', DEV_ALLOW_USER_SWITCH: 'true',
}]) {
  const env = { ...process.env, D1_DATABASE_ID: '', ACCESS_TEAM_DOMAIN: '', ACCESS_AUD: '', DEV_MODE: '', DEV_ALLOW_USER_SWITCH: '', ...options };
  const result = spawnSync(process.execPath, ['scripts/configure.mjs'], { cwd: root, env, encoding: 'utf8' });
  assert.notEqual(result.status, 0, 'Production configure must reject incomplete or development configuration');
}
console.log(`Export checks passed: ${manifest.files.length} original tracked assets, ${totalBytes.toLocaleString()} bytes; production fails closed; instructor files are outside the asset root.`);
